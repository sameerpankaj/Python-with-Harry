#Dictionaries are mutable, we can change the value associated with a key
#Dictionaries are unordered, we cannot rely on the order of items in a dictionary
#Dictionaries are indexed by keys, not by position like lists
#Dictionaries can have keys of any immutable type, such as strings, numbers, or tuples  
#Dictionaries are useful for storing and retrieving data based on keys, and they provide efficient lookups. 
#Dictionaries are commonly used in various applications, such as storing user information, counting occurrences of items, and representing structured data. 
