#pass in for loop
#The pass is a null statement in Python. It is used when you want to write code that does nothing. It is a placeholder for future code that you will add later.
# The pass statement is used when a statement is required syntactically but you do not want any command or code to execute. 
for i in range(645):
    pass # The above code will not do anything, it will just pass through the loop without executing any code.  

#The statement is useful when you are working on code and want to leave a placeholder for future code that you will add later.  

#The code below will be printed now and the code above will be not printed because of the pass statement.
while(i < 45):
    print(i)
    i += 1