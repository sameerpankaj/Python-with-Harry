#for loop is used to iterate over a sequence (like a list, tuple, string) or other iterable objects.
# It allows you to execute a block of code repeatedly for each item in the sequence.    
# Syntax:
# for variable in sequence: 
#     # code block to be executed   
# Example 1: Iterating over a list
fruits = ["apple", "banana", "cherry"]  
for fruit in fruits:
    print(fruit)    
# Example 2: Iterating over a string
for letter in "Hello":
    print(letter)
# Example 3: Using range() function to iterate over a sequence of numbers
for i in range(5):
    print(i)