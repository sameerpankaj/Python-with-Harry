def avg(): # Define a function named avg that takes no parameters
#This is a function definition. The function is named avg and it does not take any parameters. The code inside the function will be executed when the function is called.

    a = int(input("Enter the first number: "))# Prompt the user to enter the first number and convert it to an integer
    b = int(input("Enter the second number: "))# Prompt the user to enter the second number and convert it to an integer
    c = int(input("Enter the third number: "))# Prompt the user to enter the third number and convert it to an integer  
    avg = (a + b + c) / 3 # Calculate the average of the three numbers and store it in the variable avg
    print("The average is:", avg)# Print the average to the console


avg()# Call the avg function to execute the code and calculate the average of the three numbers entered by the user
#This is function call. The function avg is called, which will execute the code inside the function and calculate the average of the three numbers entered by the user. 

